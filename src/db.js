const { Pool, types } = require('pg');

/*
 * Postgres (Neon). A conexão vem de DATABASE_URL.
 *
 * Duas adaptações deixam o resto do código livre de detalhes do driver:
 *   - BIGINT chega como string por padrão no node-postgres; as datas e contagens
 *     aqui cabem com folga em Number, então convertemos na leitura.
 *   - As consultas são escritas com "?" e traduzidas para $1, $2... na hora.
 */
types.setTypeParser(types.builtins.INT8, (valor) => Number(valor));

const URL_BANCO = process.env.DATABASE_URL;
if (!URL_BANCO) {
  throw new Error(
    'DATABASE_URL não definida. Crie um banco no Neon e coloque a URL de conexão ' +
      'no arquivo .env (veja .env.example).'
  );
}

const ehLocal = /@(localhost|127\.0\.0\.1|\[::1\])[:/]/.test(URL_BANCO);

/*
 * Tiramos sslmode/channel_binding da URL e configuramos o TLS aqui.
 * O node-postgres vai mudar a interpretação desses parâmetros na v9 e passar a
 * aceitar modos mais fracos; sendo explícito, a verificação do certificado
 * continua valendo independente da versão.
 */
function semParametrosSsl(url) {
  try {
    const endereco = new URL(url);
    ['sslmode', 'channel_binding'].forEach((p) => endereco.searchParams.delete(p));
    return endereco.toString();
  } catch (_) {
    return url;
  }
}

const pool = new Pool({
  connectionString: semParametrosSsl(URL_BANCO),
  ssl: ehLocal ? false : { rejectUnauthorized: true },
  max: Number(process.env.DATABASE_POOL) || 8,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 10000,
});

pool.on('error', (erro) => console.error('Erro inesperado no pool do Postgres:', erro.message));

/** "SELECT ... WHERE id = ?" -> "SELECT ... WHERE id = $1" */
function traduzir(sql) {
  let n = 0;
  return sql.replace(/\?/g, () => `$${++n}`);
}

const ESQUEMA = `
CREATE TABLE IF NOT EXISTS quizzes (
  id          TEXT PRIMARY KEY,
  titulo      TEXT   NOT NULL,
  perguntas   JSONB  NOT NULL DEFAULT '[]'::jsonb,
  criado_em   BIGINT NOT NULL,
  alterado_em BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS partidas (
  id              TEXT PRIMARY KEY,
  quiz_id         TEXT,
  quiz_titulo     TEXT    NOT NULL,
  pin             TEXT    NOT NULL,
  total_perguntas INTEGER NOT NULL,
  iniciada_em     BIGINT  NOT NULL,
  encerrada_em    BIGINT
);
CREATE TABLE IF NOT EXISTS participantes (
  id         TEXT PRIMARY KEY,
  partida_id TEXT    NOT NULL,
  nome       TEXT    NOT NULL,
  pontos     INTEGER NOT NULL DEFAULT 0,
  acertos    INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS respostas (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partida_id      TEXT    NOT NULL,
  participante_id TEXT    NOT NULL,
  indice          INTEGER NOT NULL,
  enunciado       TEXT    NOT NULL,
  escolha         INTEGER,
  correta         INTEGER NOT NULL,
  acertou         INTEGER NOT NULL,
  pontos          INTEGER NOT NULL,
  ms              INTEGER
);
CREATE INDEX IF NOT EXISTS idx_participantes_partida ON participantes(partida_id);
CREATE INDEX IF NOT EXISTS idx_respostas_partida ON respostas(partida_id);
CREATE INDEX IF NOT EXISTS idx_partidas_data ON partidas(iniciada_em DESC);
`;

async function iniciar() {
  await pool.query(ESQUEMA);
  const { rows } = await pool.query('SELECT current_database() AS nome');
  return { url: rows[0].nome + (ehLocal ? ' (local)' : ' (remoto)') };
}

/** Uma linha ou null. */
async function um(sql, args = []) {
  const { rows } = await pool.query(traduzir(sql), args);
  return rows[0] || null;
}

/** Todas as linhas. */
async function todos(sql, args = []) {
  const { rows } = await pool.query(traduzir(sql), args);
  return rows;
}

/** Escrita simples. */
const rodar = (sql, args = []) => pool.query(traduzir(sql), args);

/** Várias escritas numa transação: ou entra tudo, ou nada. */
async function lote(comandos) {
  const cliente = await pool.connect();
  try {
    await cliente.query('BEGIN');
    for (const { sql, args } of comandos) await cliente.query(traduzir(sql), args || []);
    await cliente.query('COMMIT');
  } catch (erro) {
    await cliente.query('ROLLBACK').catch(() => {});
    throw erro;
  } finally {
    cliente.release();
  }
}

const encerrar = () => pool.end();

module.exports = { pool, iniciar, um, todos, rodar, lote, encerrar };
